//! Exact JavaScript-target dn.M hash and Heaps Perlin used by LDtk 1.5.3.
//! The float multiplication before ToInt32 deliberately preserves JS rounding.
fn js_i32(n: f64) -> i32 {
    n.trunc().rem_euclid(4294967296.) as u32 as i32
}
pub(super) fn random(seed: f64, x: i32, y: i32, max: i32) -> i32 {
    let h = js_i32(seed + x as f64 * 374761393. + y as f64 * 668265263.);
    let h = js_i32((h ^ (h >> 13)) as f64 * 1274126177.);
    (h ^ (h >> 16)) % max
}
pub(super) fn perlin(seed: f64, mut x: f64, mut y: f64, octaves: i32) -> f64 {
    let mut v = 0.;
    let mut weight = 1.;
    let mut sum = 0.;
    for octave in 0..octaves {
        let ix = js_i32(x);
        let iy = js_i32(y);
        let curve = |a: f64| {
            let a2 = a * a;
            a2 * a * (6. * a2 - 15. * a + 10.)
        };
        let xs = curve(x - ix as f64);
        let ys = curve(y - iy as f64);
        let gradient = |gx: i32, gy: i32| {
            let index = js_i32(
                (seed + octave as f64) * 1013.
                    + (gx % 50) as f64 * 1619.
                    + (gy % 50) as f64 * 31337.,
            ) as u32;
            let index = ((index ^ (index >> 8)) & 255) as usize * 3;
            GRADIENTS[index] * 2.12 * (x - gx as f64)
                + GRADIENTS[index + 1] * 2.12 * (y - gy as f64)
        };
        let ga = gradient(ix, iy);
        let gb = gradient(ix.wrapping_add(1), iy);
        let gc = gradient(ix, iy.wrapping_add(1));
        let gd = gradient(ix.wrapping_add(1), iy.wrapping_add(1));
        let a = ga + xs * (gb - ga);
        v += (a + ys * (gc + xs * (gd - gc) - a)) * weight;
        sum += weight;
        weight *= 0.5;
        x *= 2.;
        y *= 2.;
    }
    v / sum
}
